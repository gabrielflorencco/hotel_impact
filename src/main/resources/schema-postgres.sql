CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS categoria_quarto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome character varying(80) NOT NULL,
    descricao character varying(500),
    capacidade_maxima integer NOT NULL,
    quantidade_camas integer NOT NULL,
    preco_base numeric(10,2) NOT NULL,
    ativo boolean NOT NULL DEFAULT true,
    CONSTRAINT categoria_quarto_nome_key UNIQUE (nome),
    CONSTRAINT categoria_quarto_capacidade_maxima_check CHECK (capacidade_maxima >= 1),
    CONSTRAINT categoria_quarto_quantidade_camas_check CHECK (quantidade_camas >= 1)
);

CREATE TABLE IF NOT EXISTS hospede (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf character varying(11),
    nome character varying(120) NOT NULL,
    telefone character varying(20),
    email character varying(120),
    data_nascimento date,
    observacoes character varying(500),
    data_cadastro timestamp without time zone NOT NULL,
    CONSTRAINT hospede_cpf_key UNIQUE (cpf)
);

CREATE INDEX IF NOT EXISTS idx_hospede_nome ON hospede (nome);

CREATE TABLE IF NOT EXISTS item_catalogo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome character varying(80) NOT NULL,
    descricao character varying(300),
    tipo character varying(10) NOT NULL,
    preco_unitario numeric(10,2) NOT NULL,
    controla_estoque boolean NOT NULL DEFAULT false,
    estoque_atual integer NOT NULL DEFAULT 0,
    estoque_minimo integer NOT NULL DEFAULT 0,
    ativo boolean NOT NULL DEFAULT true,
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT item_catalogo_nome_key UNIQUE (nome),
    CONSTRAINT item_catalogo_tipo_check CHECK (tipo IN ('PRODUTO','SERVICO')),
    CONSTRAINT ck_item_catalogo_estoque_nao_negativo CHECK (estoque_atual >= 0)
);

CREATE TABLE IF NOT EXISTS quarto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero character varying(10) NOT NULL,
    categoria_id bigint NOT NULL,
    andar integer NOT NULL,
    capacidade_operacional integer,
    estado character varying(20) NOT NULL DEFAULT 'DISPONIVEL',
    observacoes character varying(500),
    ativo boolean NOT NULL DEFAULT true,
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT quarto_numero_key UNIQUE (numero),
    CONSTRAINT fk_quarto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria_quarto(id),
    CONSTRAINT quarto_capacidade_operacional_check CHECK (capacidade_operacional IS NULL OR capacidade_operacional >= 1),
    CONSTRAINT quarto_estado_check CHECK (estado IN ('DISPONIVEL','OCUPADO','LIMPEZA','MANUTENCAO','INTERDITADO'))
);

CREATE INDEX IF NOT EXISTS idx_quarto_estado ON quarto (estado);
CREATE INDEX IF NOT EXISTS idx_quarto_categoria ON quarto (categoria_id);

CREATE TABLE IF NOT EXISTS reserva (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(20) NOT NULL,
    hospede_id bigint NOT NULL,
    quarto_id bigint NOT NULL,
    data_check_in date NOT NULL,
    data_check_out date NOT NULL,
    quantidade_hospedes integer NOT NULL,
    valor_diaria numeric(10,2) NOT NULL,
    desconto numeric(10,2) NOT NULL DEFAULT 0,
    valor_total numeric(12,2) NOT NULL,
    data_criacao timestamp without time zone NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'PENDENTE',
    motivo_excecao character varying(300),
    observacoes character varying(500),
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT reserva_codigo_key UNIQUE (codigo),
    CONSTRAINT fk_reserva_hospede FOREIGN KEY (hospede_id) REFERENCES hospede(id),
    CONSTRAINT fk_reserva_quarto FOREIGN KEY (quarto_id) REFERENCES quarto(id),
    CONSTRAINT reserva_estado_check CHECK (estado IN ('PENDENTE','CONFIRMADA','CANCELADA','CONCLUIDA','NO_SHOW')),
    CONSTRAINT reserva_quantidade_hospedes_check CHECK (quantidade_hospedes >= 1)
);

CREATE INDEX IF NOT EXISTS idx_reserva_quarto_periodo ON reserva (quarto_id, data_check_in);
CREATE INDEX IF NOT EXISTS idx_reserva_estado ON reserva (estado);
CREATE INDEX IF NOT EXISTS idx_reserva_check_in ON reserva (data_check_in);

CREATE TABLE IF NOT EXISTS hospedagem (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id bigint NOT NULL,
    quarto_id bigint NOT NULL,
    check_in_real timestamp without time zone NOT NULL,
    check_out_real timestamp without time zone,
    estado character varying(20) NOT NULL DEFAULT 'EM_ANDAMENTO',
    motivo_excecao_encerramento character varying(300),
    observacoes character varying(500),
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT hospedagem_reserva_id_key UNIQUE (reserva_id),
    CONSTRAINT fk_hospedagem_reserva FOREIGN KEY (reserva_id) REFERENCES reserva(id),
    CONSTRAINT fk_hospedagem_quarto FOREIGN KEY (quarto_id) REFERENCES quarto(id),
    CONSTRAINT hospedagem_estado_check CHECK (estado IN ('EM_ANDAMENTO','ENCERRADA','CANCELADA'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_hospedagem_quarto_em_andamento ON hospedagem (quarto_id) WHERE (estado = 'EM_ANDAMENTO');

CREATE INDEX IF NOT EXISTS idx_hospedagem_estado ON hospedagem (estado);
CREATE INDEX IF NOT EXISTS idx_hospedagem_quarto ON hospedagem (quarto_id);

CREATE TABLE IF NOT EXISTS consumo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospedagem_id bigint NOT NULL,
    item_id bigint NOT NULL,
    quantidade integer NOT NULL,
    preco_unitario numeric(10,2) NOT NULL,
    valor_total numeric(12,2) NOT NULL,
    data_hora timestamp without time zone NOT NULL,
    estado character varying(10) NOT NULL DEFAULT 'ATIVO',
    observacoes character varying(300),
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT fk_consumo_hospedagem FOREIGN KEY (hospedagem_id) REFERENCES hospedagem(id),
    CONSTRAINT fk_consumo_item FOREIGN KEY (item_id) REFERENCES item_catalogo(id),
    CONSTRAINT consumo_estado_check CHECK (estado IN ('ATIVO','CANCELADO')),
    CONSTRAINT consumo_quantidade_check CHECK (quantidade >= 1),
    CONSTRAINT consumo_unique UNIQUE (hospedagem_id, item_id, data_hora)
);
ALTER TABLE IF EXISTS consumo ADD COLUMN IF NOT EXISTS versao bigint NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_consumo_hospedagem ON consumo (hospedagem_id);

CREATE TABLE IF NOT EXISTS pagamento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospedagem_id bigint NOT NULL,
    valor numeric(10,2) NOT NULL,
    forma character varying(20) NOT NULL,
    data_hora timestamp without time zone NOT NULL,
    estado character varying(15) NOT NULL DEFAULT 'CONFIRMADO',
    observacao character varying(300),
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT fk_pagamento_hospedagem FOREIGN KEY (hospedagem_id) REFERENCES hospedagem(id),
    CONSTRAINT pagamento_estado_check CHECK (estado IN ('CONFIRMADO','ESTORNADO')),
    CONSTRAINT pagamento_forma_check CHECK (forma IN ('DINHEIRO','PIX','CARTAO_CREDITO','CARTAO_DEBITO','OUTRO')),
    CONSTRAINT pagamento_unique UNIQUE (hospedagem_id, forma, data_hora)
);

CREATE INDEX IF NOT EXISTS idx_pagamento_hospedagem ON pagamento (hospedagem_id);
CREATE INDEX IF NOT EXISTS idx_pagamento_estado_data ON pagamento (estado, data_hora);

CREATE TABLE IF NOT EXISTS ordem_manutencao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quarto_id bigint NOT NULL,
    titulo character varying(120) NOT NULL,
    descricao character varying(500),
    prioridade character varying(10) NOT NULL DEFAULT 'MEDIA',
    estado character varying(15) NOT NULL DEFAULT 'ABERTA',
    aberta_em timestamp without time zone NOT NULL,
    concluida_em timestamp without time zone,
    interditou_quarto boolean NOT NULL DEFAULT false,
    observacoes character varying(300),
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT fk_ordem_manutencao_quarto FOREIGN KEY (quarto_id) REFERENCES quarto(id),
    CONSTRAINT ordem_manutencao_estado_check CHECK (estado IN ('ABERTA','EM_ANDAMENTO','CONCLUIDA','CANCELADA')),
    CONSTRAINT ordem_manutencao_prioridade_check CHECK (prioridade IN ('BAIXA','MEDIA','ALTA','CRITICA')),
    CONSTRAINT ordem_manutencao_unique UNIQUE (quarto_id, titulo, aberta_em)
);

CREATE INDEX IF NOT EXISTS idx_ordem_manutencao_quarto ON ordem_manutencao (quarto_id);
CREATE INDEX IF NOT EXISTS idx_ordem_manutencao_estado ON ordem_manutencao (estado);

CREATE TABLE IF NOT EXISTS tarefa_limpeza (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quarto_id bigint NOT NULL,
    estado character varying(15) NOT NULL DEFAULT 'PENDENTE',
    criada_em timestamp without time zone NOT NULL,
    concluida_em timestamp without time zone,
    observacoes character varying(300),
    versao bigint NOT NULL DEFAULT 0,
    CONSTRAINT fk_tarefa_limpeza_quarto FOREIGN KEY (quarto_id) REFERENCES quarto(id),
    CONSTRAINT tarefa_limpeza_estado_check CHECK (estado IN ('PENDENTE','EM_EXECUCAO','CONCLUIDA')),
    CONSTRAINT tarefa_limpeza_unique UNIQUE (quarto_id, criada_em)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_tarefa_limpeza_aberta ON tarefa_limpeza (quarto_id) WHERE (estado IN ('PENDENTE','EM_EXECUCAO'));

CREATE INDEX IF NOT EXISTS idx_tarefa_limpeza_quarto ON tarefa_limpeza (quarto_id);
CREATE INDEX IF NOT EXISTS idx_tarefa_limpeza_estado ON tarefa_limpeza (estado);

CREATE TABLE IF NOT EXISTS registro_auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacao character varying(30) NOT NULL,
    usuario character varying(60) NOT NULL,
    entidade_tipo character varying(30) NOT NULL,
    entidade_id bigint NOT NULL,
    data_hora timestamp without time zone NOT NULL,
    detalhe character varying(300),
    CONSTRAINT registro_auditoria_operacao_check CHECK (operacao IN (
        'RESERVA_CRIADA','RESERVA_EDITADA','RESERVA_CANCELADA','RESERVA_NO_SHOW',
        'CHECK_IN','CHECK_OUT',
        'CONSUMO_LANCADO','CONSUMO_CANCELADO',
        'PAGAMENTO_REGISTRADO','PAGAMENTO_ESTORNADO',
        'LIMPEZA_INICIADA','LIMPEZA_CONCLUIDA',
        'MANUTENCAO_ABERTA','MANUTENCAO_INICIADA','MANUTENCAO_CONCLUIDA','MANUTENCAO_CANCELADA'
    )),
    CONSTRAINT registro_auditoria_unique UNIQUE (operacao, usuario, entidade_tipo, entidade_id, data_hora)
);

CREATE INDEX IF NOT EXISTS idx_auditoria_data ON registro_auditoria (data_hora);
CREATE INDEX IF NOT EXISTS idx_auditoria_entidade ON registro_auditoria (entidade_tipo, entidade_id);